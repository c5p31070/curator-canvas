// Export a static public preset; no upload or Supabase write is performed.
document.addEventListener('DOMContentLoaded', () => {
    document.getElementById('btnExportGuestLighting')?.addEventListener('click', () => {
        if (!isAdminMode || window.CURATOR_GUEST?.active || window.CURATOR_ROLE === 'viewer' || isTransitioning || isUndoRedoOperation || !window.isDiagramReady?.()) return;
        const status = document.getElementById('guestLightingExportStatus');
        if (!(Number.isFinite(configuredScale) && configuredScale > 0)) {
            status.textContent = '先に平面図の縮尺を設定してください。';
            return;
        }
        window.cancelLightingPlacement?.();
        window.flushPendingItemEditHistory?.();
        captureCurrentCanvasState();
        const source = window.getVenueLightingData?.() || {};
        const venueLightingData = {};
        let rails = 0, fixed = 0;
        Object.keys(FLOOR_PLANS).forEach(id => {
            const objects = (source[id]?.objects || []).filter(object => !object.excludeFromExport &&
                (object.isLightRail || (object.isLightObject && object.lightKind === 'fixed')));
            venueLightingData[id] = { objects: objects.map(object => ({ ...object, visible: true, lightOn: true })) };
            rails += objects.filter(object => object.isLightRail).length;
            fixed += objects.filter(object => object.lightKind === 'fixed').length;
        });
        if (!rails) {
            status.textContent = '配布するレールがありません。先にレールを登録してください。';
            return;
        }
        const preset = { version: crypto.randomUUID(), scale: configuredScale, venueLightingData };
        const contents = '// Public guest venue preset. Generated by Curator-Canvas.\nwindow.CURATOR_GUEST_VENUE_PRESET = '
            + JSON.stringify(preset, null, 2) + ';\n';
        const url = URL.createObjectURL(new Blob([contents], { type: 'text/javascript;charset=utf-8' }));
        const link = document.createElement('a');
        link.href = url;
        link.download = 'guest-venue-preset.js';
        document.body.appendChild(link);
        link.click();
        link.remove();
        setTimeout(() => URL.revokeObjectURL(url), 1000);
        status.textContent = `レール${rails}本・固定ライト${fixed}個を書き出しました。js/guest-venue-preset.jsをこのファイルで置き換え、公開してください。`;
    });
});
